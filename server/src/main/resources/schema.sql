CREATE TABLE IF NOT EXISTS products (
    id BIGINT PRIMARY KEY,
    name VARCHAR(150) NOT NULL,
    category VARCHAR(60) NOT NULL,
    description VARCHAR(1000) NOT NULL,
    price_clp INT NOT NULL CHECK (price_clp > 0),
    weight_grams INT NOT NULL CHECK (weight_grams > 0),
    stock INT NOT NULL CHECK (stock >= 0),
    image_key VARCHAR(255) NOT NULL
);

CREATE TABLE IF NOT EXISTS demo_orders (
    id VARCHAR(36) PRIMARY KEY,
    request_id VARCHAR(36) NOT NULL UNIQUE,
    customer_alias VARCHAR(80) NOT NULL,
    created_at BIGINT NOT NULL,
    status VARCHAR(20) NOT NULL,
    total_clp BIGINT NOT NULL CHECK (total_clp > 0)
);

CREATE TABLE IF NOT EXISTS demo_order_lines (
    order_id VARCHAR(36) NOT NULL REFERENCES demo_orders(id),
    product_id BIGINT NOT NULL REFERENCES products(id),
    product_name VARCHAR(150) NOT NULL,
    quantity INT NOT NULL CHECK (quantity > 0),
    unit_price_clp INT NOT NULL CHECK (unit_price_clp > 0),
    PRIMARY KEY (order_id, product_id)
);

CREATE TABLE IF NOT EXISTS inventory_movements (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id BIGINT NOT NULL REFERENCES products(id),
    change_qty INT NOT NULL CHECK (change_qty <> 0),
    before_stock INT NOT NULL,
    after_stock INT NOT NULL CHECK (after_stock >= 0),
    note VARCHAR(200) NOT NULL,
    created_at BIGINT NOT NULL
);

